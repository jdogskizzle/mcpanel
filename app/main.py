# ---------------------------------------------------------------- helpers

def load_servers() -> dict:
    return (yaml.safe_load(SERVERS_FILE.read_text()) or {}).get("servers") or {}


def write_owned(path: Path, text: str) -> None:
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text)
    os.chown(tmp, *OWNER)
    tmp.replace(path)


def save_servers(servers: dict) -> None:
    write_owned(SERVERS_FILE, SERVERS_HEADER + yaml.safe_dump({"servers": servers}, sort_keys=False))


def restart_policy(c: dict) -> str:
    # autostart on: start at boot unless stopped by hand. Off: only start when asked.
    return "unless-stopped" if c.get("autostart", True) else "no"


def set_properties(path: Path, values: dict) -> None:
    """Set keys in a server.properties file, keeping everything else."""
    lines = path.read_text().splitlines() if path.exists() else []
    todo = dict(values)
    for i, line in enumerate(lines):
        key = line.split("=", 1)[0].strip()
        if not line.startswith("#") and key in todo:
            lines[i] = f"{key}={todo.pop(key)}"
    lines += [f"{k}={v}" for k, v in todo.items()]
    path.write_text("\n".join(lines) + "\n")
    os.chown(path, *OWNER)


def uses_network(c: dict) -> bool:
    # "apps_network" is the older name of the setting.
    return bool(c.get("network", c.get("apps_network")))


def build_compose(servers: dict) -> dict:
    services = {}
    for name, c in servers.items():
        policy = restart_policy(c)
        env = {"EULA": "TRUE", "UID": str(OWNER[0]), "GID": str(OWNER[1]), "TZ": TZ,
               "RCON_PASSWORD": "${RCON_PASSWORD}", "TYPE": c["type"]}
        if c["type"] == "CUSTOM":
            env["CUSTOM_SERVER"] = f"/data/{c['jar']}"
        else:
            env["VERSION"] = str(c["version"])
        env["SERVER_PORT"] = str(c["port"])
        env["MEMORY"] = c["memory"]
        if c.get("autopause"):
            env.update({"ENABLE_AUTOPAUSE": "TRUE", "AUTOPAUSE_TIMEOUT_EST": "300", "MAX_TICK_TIME": "-1"})
        ports = [f"{c['port']}:{c['port']}"]
        if c.get("bedrock_port"):
            ports.append(f"{c['bedrock_port']}:{c['bedrock_port']}/udp")
        svc = {"image": f"itzg/minecraft-server:{c.get('java', 'java25')}",
               "container_name": f"mc-{name}", "restart": policy,
               "tty": True, "stdin_open": True, "environment": env,
               "ports": ports, "volumes": [f"./{name}:/data"]}
        if uses_network(c):
            if not NETWORK:
                raise RuntimeError(f"{name} asks for the external network, but NETWORK isn't set")
            svc["networks"] = ["default", NETWORK]
        services[name] = svc
    for name, c in servers.items():
        services[f"backup-{name}"] = {
            "image": "itzg/mc-backup", "container_name": f"mc-backup-{name}",
            "restart": restart_policy(c),
            "environment": {"BACKUP_INTERVAL": "24h", "INITIAL_DELAY": "10m",
                            "PRUNE_BACKUPS_DAYS": "7", "PAUSE_IF_NO_PLAYERS": "true",
                            "RCON_PASSWORD": "${RCON_PASSWORD}", "TZ": TZ,
                            "RCON_HOST": f"mc-{name}",
                            "EXCLUDES": c.get("backup_excludes") or DEFAULT_EXCLUDES},
            "volumes": [f"./{name}:/data:ro", f"{BACKUP_DIR}/{name}:/backups"],
            "depends_on": [name]}
    out = {"name": PROJECT, "services": services}
    if any(uses_network(c) for c in servers.values()):
        out["networks"] = {NETWORK: {"external": True}}
    return out


def compose_cmd(*args, file: Path = COMPOSE_FILE) -> list[str]:
    return ["docker", "compose", "-p", PROJECT, "--project-directory", str(MC_DIR), "-f", str(file), *args]


def run(cmd: list[str], timeout: int = 60) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


# ---------------------------------------------------------------- jobs

def log(job: dict, msg: str) -> None:
    job["log"].append(f"{datetime.now():%H:%M:%S}  {msg}")


def sh(job: dict, cmd: list[str], timeout: int = 1800, check: bool = True) -> subprocess.CompletedProcess:
    log(job, "$ " + " ".join(cmd))
    p = run(cmd, timeout=timeout)
    out = (p.stdout + p.stderr).strip()
    if out:
        job["log"].extend("    " + line for line in out.splitlines()[-40:])
    if check and p.returncode != 0:
        raise RuntimeError(f"command failed (exit {p.returncode})")
    return p


def compose(job: dict, *args) -> None:
    sh(job, compose_cmd(*args))


def write_compose(job: dict, servers: dict) -> None:
    text = COMPOSE_HEADER + yaml.safe_dump(build_compose(servers), sort_keys=False)
    new = MC_DIR / ".docker-compose.yml.new"
    new.write_text(text)
    p = run(compose_cmd("config", "-q", file=new))
    if p.returncode != 0:
        new.unlink()
        raise RuntimeError("generated compose file is invalid: " + p.stderr.strip())
    if COMPOSE_FILE.exists():
        shutil.copy2(COMPOSE_FILE, MC_DIR / ".docker-compose.yml.prev")
    os.chown(new, *OWNER)
    new.replace(COMPOSE_FILE)
    log(job, "docker-compose.yml regenerated from servers.yml")


def start_job(server: str, action: str, fn, *args) -> dict:
    with busy_lock:
        if server in busy:
            raise HTTPException(409, f"{server} is already busy with another task")
        busy.add(server)
    job = {"id": uuid.uuid4().hex[:8], "server": server, "action": action, "status": "running",
           "log": [], "started": time.time(), "ended": None}
    jobs[job["id"]] = job
    for old in sorted(jobs.values(), key=lambda j: j["started"])[:-30]:
        jobs.pop(old["id"], None)

    def target():
        try:
            fn(job, *args)
            job["status"] = "done"
            log(job, "Finished.")
        except Exception as e:  # noqa: BLE001 - shown to the user
            job["status"] = "failed"
            log(job, f"FAILED: {e}")
        finally:
            job["ended"] = time.time()
            with busy_lock:
                busy.discard(server)
            refresh_status()

    threading.Thread(target=target, daemon=True).start()
    return job


# ---------------------------------------------------------------- status

status_cache: dict = {"servers": {}, "updated": 0}


def refresh_status() -> None:
    servers = load_servers()
    states = {}
    p = run(["docker", "ps", "-a", "--filter", f"label=com.docker.compose.project={PROJECT}",
             "--format", "{{json .}}"])
    for line in p.stdout.splitlines():
        d = json.loads(line)
        states[d["Names"]] = d
    stats = {}
    p = run(["docker", "stats", "--no-stream", "--format", "{{json .}}"], timeout=30)
    for line in p.stdout.splitlines():
        d = json.loads(line)
        stats[d["Name"]] = d
    out = {}
    for name, c in servers.items():
        cname = f"mc-{name}"
        st = states.get(cname)
        paused = (MC_DIR / name / ".paused").exists()
        if not st:
            state = "missing"
        elif st["State"] != "running":
            state = "stopped"
        elif paused:
            state = "sleeping"
        elif "health: starting" in st["Status"]:
            state = "starting"
        else:
            state = "running"
        info = {"state": state, "detail": st["Status"] if st else "not created",
                "players": None, "max_players": None, "running_version": None,
                "memory": stats.get(cname, {}).get("MemUsage") if state != "stopped" else None,
                "cpu": stats.get(cname, {}).get("CPUPerc") if state != "stopped" else None}
        if state == "running":
            # Pings over localhost don't wake or keep awake an autopaused server.
            m = run(["docker", "exec", cname, "mc-monitor", "status", "--host", "localhost",
                     "--port", str(c["port"])], timeout=10)
            mm = re.search(r"version=(.*?) online=(\d+) max=(\d+)", m.stdout)
            if mm:
                info.update(running_version=mm.group(1), players=int(mm.group(2)),
                            max_players=int(mm.group(3)))
        out[name] = info
    status_cache.update(servers=out, updated=time.time())


def status_loop() -> None:
    while True:
        try:
            refresh_status()
        except Exception:  # noqa: BLE001 - keep looping
            pass
        time.sleep(10)


threading.Thread(target=status_loop, daemon=True).start()


def list_backups(name: str) -> list[dict]:
    d = BACKUP_DIR / name
    if not d.is_dir():
        return []
    items = []
    for f in d.iterdir():
        if f.is_symlink() or not BACKUP_RE.match(f.name):
            continue
        s = f.stat()
        items.append({"file": f.name, "size": s.st_size, "time": s.st_mtime})
    return sorted(items, key=lambda b: b["time"], reverse=True)


# ---------------------------------------------------------------- actions

def get_server(name: str) -> dict:
    servers = load_servers()
    if name not in servers:
        raise HTTPException(404, f"unknown server {name}")
    return servers[name]


def container_running(name: str) -> bool:
    p = run(["docker", "inspect", "-f", "{{.State.Running}}", f"mc-{name}"])
    return p.stdout.strip() == "true"


def do_power(job: dict, name: str, action: str) -> None:
    if action == "start":
        compose(job, "up", "-d", name, f"backup-{name}")
    elif action == "stop":
        compose(job, "stop", f"backup-{name}", name)
    else:
        compose(job, "restart", name)


def make_backup(job: dict, name: str) -> None:
    if container_running(name) and container_running(f"backup-{name}"):
        log(job, "Backing up the running server (saves the world first)...")
        sh(job, ["docker", "exec", "-e", "PAUSE_IF_NO_PLAYERS=false", f"mc-backup-{name}", "backup", "now"])
        return
    log(job, "Server is stopped; backing up its folder directly...")
    c = get_server(name)
    dest = BACKUP_DIR / name
    dest.mkdir(parents=True, exist_ok=True)
    out = dest / f"world-{datetime.now():%Y%m%d-%H%M%S}.tar.gz"
    excludes = [f"--exclude={p}" for p in (c.get("backup_excludes") or DEFAULT_EXCLUDES).split(",") if p]
    sh(job, ["tar", "-czf", str(out), *excludes, "-C", str(MC_DIR / name), "."])
    os.chown(out, *OWNER)


def do_backup(job: dict, name: str) -> None:
    make_backup(job, name)


def do_restore(job: dict, name: str, fname: str) -> None:
    src = BACKUP_DIR / name / fname
    folder = MC_DIR / name
    log(job, f"Restoring {fname}")
    log(job, "Reading the backup's file list...")
    p = run(["tar", "-tzf", str(src)], timeout=600)
    if p.returncode != 0:
        raise RuntimeError("could not read the backup: " + p.stderr.strip()[-300:])
    tops = set()
    for line in p.stdout.splitlines():
        parts = [x for x in line.split("/") if x not in ("", ".")]
        if not parts:
            continue
        if line.startswith("/") or ".." in parts:
            raise RuntimeError(f"unsafe path in backup: {line}")
        tops.add(parts[0])
    if not tops:
        raise RuntimeError("backup is empty")
    log(job, f"Backup contains: {', '.join(sorted(tops))}")

    compose(job, "stop", f"backup-{name}", name)
    safety = SAFETY_DIR / f"{name}-{datetime.now():%Y%m%d-%H%M%S}"
    safety.mkdir(parents=True)
    moved = []
    for top in sorted(tops):
        p_ = folder / top
        if p_.exists() or p_.is_symlink():
            shutil.move(str(p_), str(safety / top))
            moved.append(top)
    log(job, f"Current files moved aside to {safety} ({len(moved)} items)")
    sh(job, ["tar", "-xzf", str(src), "--no-same-owner", "-C", str(folder)], timeout=1800)
    sh(job, ["chown", "-R", f"{OWNER[0]}:{OWNER[1]}", str(folder), str(SAFETY_DIR)])
    old = sorted(SAFETY_DIR.glob(f"{name}-*"))[:-KEEP_SAFETY]
    for o in old:
        shutil.rmtree(o, ignore_errors=True)
        log(job, f"Removed old pre-restore copy {o.name}")
    compose(job, "up", "-d", name, f"backup-{name}")


def do_change(job: dict, name: str, body: "VersionBody") -> None:
    with config_lock:
        servers = load_servers()
        prev = json.loads(json.dumps(servers))
    if container_running(name):
        make_backup(job, name)
    with config_lock:
        servers = load_servers()
        c = servers[name]
        c["type"] = body.type
        if body.type == "CUSTOM":
            c["jar"] = body.jar
            c.pop("version", None)
        else:
            c["version"] = body.version
            c.pop("jar", None)
        c["java"] = body.java
        c["memory"] = body.memory
        save_servers(servers)
        try:
            write_compose(job, servers)
        except Exception:
            save_servers(prev)
            raise
    log(job, f"{name}: {body.type} {body.jar if body.type == 'CUSTOM' else body.version}, "
             f"{body.java}, {body.memory}")
    try:
        compose(job, "up", "-d", name, f"backup-{name}")
    except Exception:
        log(job, "Start failed; putting the previous settings back.")
        with config_lock:
            save_servers(prev)
            write_compose(job, prev)
        compose(job, "up", "-d", name, f"backup-{name}")
        raise


def do_autostart(job: dict, name: str, enabled: bool) -> None:
    with config_lock:
        servers = load_servers()
        servers[name]["autostart"] = enabled
        save_servers(servers)
        write_compose(job, servers)
    policy = restart_policy(servers[name])
    # Change the policy in place so the running server isn't restarted.
    for cname in (f"mc-{name}", f"mc-backup-{name}"):
        if run(["docker", "inspect", cname]).returncode == 0:
            sh(job, ["docker", "update", f"--restart={policy}", cname])
    log(job, f"{name} will {'start at boot' if enabled else 'only start when you press Start'}.")


def do_add(job: dict, name: str, body: "AddBody") -> None:
    folder = MC_DIR / name
    if body.import_from:
        log(job, f"Copying {body.import_from} into {folder}")
        sh(job, ["rsync", "-a", f"{body.import_from}/", f"{folder}/"], timeout=3600)
    else:
        folder.mkdir()
    sh(job, ["chown", "-R", f"{OWNER[0]}:{OWNER[1]}", str(folder)])
    props = {}
    if body.difficulty:
        props["difficulty"] = body.difficulty
    if body.gamemode:
        props["gamemode"] = body.gamemode
    if not body.import_from:
        props["level-seed"] = body.seed or ""
    if props:
        set_properties(folder / "server.properties", props)
        log(job, "server.properties: " + ", ".join(f"{k}={v or '(random)'}" for k, v in props.items()))
    (BACKUP_DIR / name).mkdir(parents=True, exist_ok=True)
    os.chown(BACKUP_DIR / name, *OWNER)
    with config_lock:
        servers = load_servers()
        prev = json.loads(json.dumps(servers))
        entry = {"type": body.type}
        if body.type == "CUSTOM":
            entry["jar"] = body.jar
        else:
            entry["version"] = body.version
        entry.update({"java": body.java, "memory": body.memory, "port": body.port,
                      "autopause": body.autopause, "autostart": body.autostart,
                      "backup_excludes": DEFAULT_EXCLUDES})
        servers[name] = entry
        save_servers(servers)
        try:
            write_compose(job, servers)
        except Exception:
            save_servers(prev)
            raise
    try:
        compose(job, "up", "-d", name, f"backup-{name}")
    except Exception:
        log(job, "Start failed; removing it from servers.yml again (its folder is kept).")
        sh(job, compose_cmd("rm", "-sf", name, f"backup-{name}"), check=False)
        with config_lock:
            save_servers(prev)
            write_compose(job, prev)
        raise
    log(job, f"Remember to forward TCP port {body.port} to {FORWARD_TO or 'this machine on your router'} "
             "if players outside your network should join.")


# ---------------------------------------------------------------- API models

class RestoreBody(BaseModel):
    file: str


class VersionBody(BaseModel):
    type: str
    version: str | None = None
    jar: str | None = None
    java: str = "java25"
    memory: str


class AddBody(VersionBody):
    name: str
    port: int
    autopause: bool = True
    autostart: bool = True
    import_from: str | None = None
    difficulty: str | None = None   # None/"" = keep (copied server) or Minecraft default
    gamemode: str | None = None
    seed: str | None = None         # blank = random


class AutostartBody(BaseModel):
    enabled: bool


DIFFICULTIES = ["peaceful", "easy", "normal", "hard"]
GAMEMODES = ["survival", "creative", "adventure", "spectator"]
SEED_RE = re.compile(r"^-?[\w .,!?'-]{0,64}$")


def check_version_body(body: VersionBody, folder: Path) -> None:
    if body.type not in TYPES:
        raise HTTPException(400, "unknown server type")
    if body.java not in JAVA:
        raise HTTPException(400, "unknown Java version")
    if not MEM_RE.match(body.memory):
        raise HTTPException(400, "memory must look like 2G or 1536M")
    if body.type == "CUSTOM":
        if not body.jar or not JAR_RE.match(body.jar):
            raise HTTPException(400, "choose a jar file")
        if not (folder / body.jar).is_file():
            raise HTTPException(400, f"{body.jar} is not in the server folder")
    elif not body.version or not VERSION_RE.match(body.version):
        raise HTTPException(400, "enter a version, e.g. 26.2 or LATEST")


# ---------------------------------------------------------------- API

@app.get("/")
def index():
    return FileResponse(Path(__file__).parent / "static" / "index.html")


@app.get("/api/servers")
def api_servers():
    servers = load_servers()
    out = []
    for name, c in servers.items():
        out.append({"name": name, "config": c,
                    "status": status_cache["servers"].get(name, {"state": "unknown"}),
                    "busy": name in busy, "backups": list_backups(name)})
    return {"servers": out, "updated": status_cache["updated"]}


@app.post("/api/servers/{name}/restore")
def api_restore(name: str, body: RestoreBody):
    get_server(name)
    f = BACKUP_DIR / name / body.file
    if not BACKUP_RE.match(body.file) or f.is_symlink() or not f.is_file():
        raise HTTPException(400, "backup not found")
    return start_job(name, "restore", do_restore, name, body.file)


@app.post("/api/servers/{name}/version")
def api_version(name: str, body: VersionBody):
    get_server(name)
    check_version_body(body, MC_DIR / name)
    return start_job(name, "change version", do_change, name, body)


@app.post("/api/servers/{name}/autostart")
def api_autostart(name: str, body: AutostartBody):
    get_server(name)
    return start_job(name, "autostart " + ("on" if body.enabled else "off"), do_autostart, name, body.enabled)


# Registered after /restore, /version and /autostart so it doesn't swallow them.
@app.post("/api/servers/{name}/{action}")
def api_action(name: str, action: str):
    get_server(name)
    if action in ("start", "stop", "restart"):
        return start_job(name, action, do_power, name, action)
    if action == "backup":
        return start_job(name, "backup", do_backup, name)
    raise HTTPException(404, "unknown action")


@app.post("/api/servers")
def api_add(body: AddBody):
    if not NAME_RE.match(body.name):
        raise HTTPException(400, "name: lowercase letters, digits and dashes, 2-24 characters")
    servers = load_servers()
    if body.name in servers or (MC_DIR / body.name).exists() or body.name.startswith("backup"):
        raise HTTPException(400, "that name is already used")
    if not 1024 < body.port < 65536:
        raise HTTPException(400, "port must be between 1025 and 65535")
    used = {c["port"] for c in servers.values()} | {c.get("bedrock_port") for c in servers.values()}
    if body.port in used:
        raise HTTPException(400, f"port {body.port} is already used by another server")
    if body.import_from:
        src = Path(body.import_from).resolve()
        if src not in [Path(p).resolve() for p in importable_folders()]:
            raise HTTPException(400, "unknown folder to copy from")
        body.import_from = str(src)
    if body.difficulty and body.difficulty not in DIFFICULTIES:
        raise HTTPException(400, "unknown difficulty")
    if body.gamemode and body.gamemode not in GAMEMODES:
        raise HTTPException(400, "unknown game mode")
    body.seed = (body.seed or "").strip()
    if not SEED_RE.match(body.seed):
        raise HTTPException(400, "seed: up to 64 letters, digits, spaces or simple punctuation")
    if body.type == "CUSTOM" and not body.import_from:
        raise HTTPException(400, "a custom jar needs a folder to copy from (pick one under 'Start from')")
    check_version_body(body, Path(body.import_from) if body.import_from else MC_DIR / body.name)
    return start_job(body.name, "add server", do_add, body.name, body)


