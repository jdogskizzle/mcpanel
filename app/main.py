def env(name: str, required: bool = True) -> str:
    """Read a setting from the environment (set in docker-compose.yml)."""
    value = os.environ.get(name, "").strip()
    if required and not value:
        raise SystemExit(f"mcpanel: environment variable {name} is required (see docker-compose.yml)")
    return value


def env_int(name: str) -> int:
    value = env(name)
    if not value.isdigit():
        raise SystemExit(f"mcpanel: {name} must be a number, got {value!r}")
    return int(value)


