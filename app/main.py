@app.get("/api/versions/{type_}")
def api_versions(type_: str):
    type_ = type_.upper()
    if type_ not in TYPES or type_ == "CUSTOM":
        return []
    cached = version_cache.get(type_)
    if cached and time.time() - cached[0] < 3600:
        return cached[1]
    versions: list[str] = []
    try:
        if type_ == "PAPER":
            try:
                d = fetch_json("https://fill.papermc.io/v3/projects/paper")
                versions = [v for group in d["versions"].values() for v in group]
            except Exception:  # noqa: BLE001 - fall back to the old API
                versions = list(reversed(fetch_json("https://api.papermc.io/v2/projects/paper")["versions"]))
        elif type_ == "FABRIC":
            versions = [v["version"] for v in fetch_json("https://meta.fabricmc.net/v2/versions/game") if v["stable"]]
        else:
            d = fetch_json("https://piston-meta.mojang.com/mc/game/version_manifest_v2.json")
            versions = [v["id"] for v in d["versions"] if v["type"] == "release"]
    except Exception:  # noqa: BLE001 - UI still allows typing a version
        versions = []
    versions = ["LATEST"] + versions[:60]
    version_cache[type_] = (time.time(), versions)
    return versions
