def importable_folders() -> list[str]:
    found = []
    if not IMPORT_DIR or not IMPORT_DIR.is_dir():
        return found
    for props in sorted(IMPORT_DIR.glob("**/server.properties")):
        rel = props.parent.relative_to(IMPORT_DIR)
        if len(rel.parts) <= 3:
            found.append(str(props.parent))
    return found


